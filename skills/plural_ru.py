"""Склонение существительных при числительных — то, чего нет в английской ветке.

Английскому хватает двух форм (`requirement` / `requirements`), и весь код `main`
написан под них: `noun = "requirement" if count == 1 else "requirements"`. Русскому
нужны ТРИ, и подставить сюда две — значит печатать «2 требований» в документе,
который читает спонсор.

Этот модуль существует только в ветке `ru`. Он намеренно не добавлен в `common.py`:
так `common.py` остаётся побайтово идентичным `main` по логике, и сверка порта не
получает постоянного шума в самом используемом файле проекта. Расхождение с `main`
остаётся только там, где функция вызывается, — и каждое такое место объяснимо одной
причиной: английскому там хватало двух форм.

    plural_ru(1, "требование", "требования", "требований")  -> "требование"
    plural_ru(3, ...)                                       -> "требования"
    plural_ru(5, ...)                                       -> "требований"
    plural_ru(11, ...)                                      -> "требований"

# Copyright (c) 2026 Anatoly Chaussky. AI-powered Platform AInalyst. Licensed under AGPL v3. Commercial licensing: chaussky@gmail.com
"""


def plural_ru(n: int, one: str, few: str, many: str) -> str:
    """Форма существительного при числе `n`.

    Правило русского языка, а не эвристика: 11–14 склоняются как «много» независимо
    от последней цифры, поэтому проверка сотен идёт первой. Именно на этом месте
    ошибаются самые распространённые реализации — «11 требования».
    """
    n = abs(int(n))
    if n % 100 in (11, 12, 13, 14):
        return many
    last = n % 10
    if last == 1:
        return one
    if last in (2, 3, 4):
        return few
    return many


def with_plural(n: int, one: str, few: str, many: str) -> str:
    """«3 требования» — число вместе с правильной формой, одной строкой."""
    return f"{n} {plural_ru(n, one, few, many)}"
